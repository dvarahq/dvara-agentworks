package com.dvarahq.agentworks.identity.web;

import com.dvarahq.agentworks.api.web.Page;
import com.dvarahq.agentworks.domain.identity.AuthenticatedPrincipal;
import com.dvarahq.agentworks.domain.identity.WorkspaceRole;
import com.dvarahq.agentworks.identity.IdentityException;
import com.dvarahq.agentworks.identity.IdentityService;
import com.dvarahq.agentworks.identity.IdentityService.IssuedPassword;
import com.dvarahq.agentworks.storage.identity.IdentityRows.UserRow;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.util.UriComponentsBuilder;

import java.time.Instant;
import java.util.Objects;
import java.util.UUID;

/**
 * Organization user administration by an organization administrator's interactive session. Temporary passwords
 * are generated by the server, returned once, and must be changed at the next sign-in.
 */
@RestController
@RequestMapping(path = "/api/v1/users", produces = MediaType.APPLICATION_JSON_VALUE)
public final class UserAdministrationController {
    /** @param workspaceRole when present, also grants this role in the administrator's current workspace */
    public record CreateUser(String username, String displayName, String organizationRole, String workspaceRole) {}

    public record UserView(UUID id, UUID organizationId, String username, String displayName, String organizationRole,
            String status, boolean mustChangePassword, Instant lockedUntil, Instant createdAt) {
        static UserView of(UserRow row) {
            return new UserView(row.id(), row.organizationId(), row.username(), row.displayName(),
                    row.organizationRole(), row.status(), row.mustChangePassword(), row.lockedUntil(), row.createdAt());
        }
    }

    /** Returned once: the temporary password is never stored in plain text or shown again. */
    public record IssuedCredential(UserView user, String temporaryPassword) {
        static IssuedCredential of(IssuedPassword issued) {
            return new IssuedCredential(UserView.of(issued.user()), issued.temporaryPassword());
        }

        @Override
        public String toString() {
            return "IssuedCredential[user=" + user.id() + "]";
        }
    }


    private final IdentityService identities;

    public UserAdministrationController(IdentityService identities) {
        this.identities = Objects.requireNonNull(identities, "identities");
    }

    @GetMapping
    public Page<UserView> list(@AuthenticationPrincipal AuthenticatedPrincipal admin) {
        // Identity collections are bounded and never paged.
        return Page.of(identities.listUsers(admin).stream().map(UserView::of).toList());
    }

    @PostMapping(consumes = MediaType.APPLICATION_JSON_VALUE)
    public ResponseEntity<IssuedCredential> create(@AuthenticationPrincipal AuthenticatedPrincipal admin,
            @RequestBody CreateUser body) {
        WorkspaceRole workspaceRole = body.workspaceRole() == null ? null : WorkspaceRole.parse(body.workspaceRole())
                .orElseThrow(() -> new IdentityException(IdentityException.INVALID_REQUEST,
                        "The workspace role must be ADMIN, AUTHOR, OPERATOR, or VIEWER."));
        IssuedPassword issued = identities.createUser(admin, body.username(), body.displayName(),
                body.organizationRole(), workspaceRole);
        return ResponseEntity.status(HttpStatus.CREATED)
                .location(UriComponentsBuilder.fromPath("/api/v1/users/{id}").build(issued.user().id()))
                .body(IssuedCredential.of(issued));
    }

    /** Issues a temporary password and revokes every session and API token of the user. */
    @PostMapping("/{id}/password-reset")
    public IssuedCredential resetPassword(@AuthenticationPrincipal AuthenticatedPrincipal admin, @PathVariable UUID id) {
        return IssuedCredential.of(identities.resetPassword(admin, id));
    }

    @PostMapping("/{id}/disable")
    public UserView disable(@AuthenticationPrincipal AuthenticatedPrincipal admin, @PathVariable UUID id) {
        return UserView.of(identities.disable(admin, id));
    }

    @PostMapping("/{id}/enable")
    public UserView enable(@AuthenticationPrincipal AuthenticatedPrincipal admin, @PathVariable UUID id) {
        return UserView.of(identities.enable(admin, id));
    }
}
