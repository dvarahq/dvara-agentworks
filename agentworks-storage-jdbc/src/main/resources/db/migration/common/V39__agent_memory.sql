-- Issue #49: explicit conversation/working memory authority and content-free provenance.
create table agent_memory_scope_revision (
    workspace_id uuid not null,
    memory_kind varchar(16) not null,
    scope_id uuid not null,
    revision bigint default 0 not null,
    updated_at timestamp with time zone not null,
    primary key (workspace_id, memory_kind, scope_id),
    constraint agent_memory_scope_kind_ck check (memory_kind in ('CONVERSATION', 'WORKING')),
    constraint agent_memory_scope_revision_ck check (revision >= 0)
);

create table agent_memory_record (
    workspace_id uuid not null,
    id uuid not null,
    definition_id uuid not null,
    memory_kind varchar(16) not null,
    scope_id uuid not null,
    session_id uuid,
    run_id uuid not null,
    release_id uuid not null,
    revision_id uuid not null,
    role varchar(32) not null,
    idempotency_key varchar(128) not null,
    request_digest varchar(71) not null,
    content_text text not null,
    content_digest varchar(71) not null,
    created_at timestamp with time zone not null,
    expires_at timestamp with time zone not null,
    primary key (workspace_id, id),
    unique (workspace_id, run_id, idempotency_key),
    foreign key (workspace_id, definition_id) references agent_definition(workspace_id, id),
    foreign key (workspace_id, run_id) references agent_run(workspace_id, id),
    constraint agent_memory_record_kind_ck check (memory_kind in ('CONVERSATION', 'WORKING')),
    constraint agent_memory_record_scope_ck check (
        (memory_kind = 'CONVERSATION' and session_id is not null and scope_id = session_id)
        or (memory_kind = 'WORKING' and session_id is null and scope_id = run_id)),
    constraint agent_memory_record_digest_ck check (
        char_length(request_digest) = 71 and request_digest like 'sha256:%'
        and char_length(content_digest) = 71 and content_digest like 'sha256:%'),
    constraint agent_memory_record_content_ck check (
        char_length(content_text) between 1 and 65536 and expires_at > created_at)
);
create index agent_memory_record_read_idx
    on agent_memory_record(workspace_id, memory_kind, scope_id, expires_at, created_at desc, id desc);
create index agent_memory_record_expiry_idx
    on agent_memory_record(workspace_id, expires_at, id);

create table agent_memory_provenance (
    sequence bigint generated by default as identity,
    workspace_id uuid not null,
    run_id uuid not null,
    memory_kind varchar(16) not null,
    scope_id uuid not null,
    operation varchar(16) not null,
    record_count integer not null,
    records_digest varchar(71) not null,
    actor_id uuid not null,
    occurred_at timestamp with time zone not null,
    primary key (sequence),
    foreign key (workspace_id, run_id) references agent_run(workspace_id, id),
    constraint agent_memory_provenance_kind_ck check (memory_kind in ('CONVERSATION', 'WORKING')),
    constraint agent_memory_provenance_operation_ck check (operation in ('READ', 'WRITE', 'DELETE', 'EXPIRE')),
    constraint agent_memory_provenance_count_ck check (record_count >= 0),
    constraint agent_memory_provenance_digest_ck check (
        char_length(records_digest) = 71 and records_digest like 'sha256:%')
);
create index agent_memory_provenance_scope_idx
    on agent_memory_provenance(workspace_id, memory_kind, scope_id, sequence);
